#!/usr/bin/env python3
"""Generate C++ parameter structs and UI metadata from config/parameters.schema.json."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "config" / "parameters.schema.json"
OUTPUT = ROOT / "include" / "core" / "parameters_generated.h"


def cpp_literal(field):
    value = field["default"]
    kind = field["type"]
    if kind == "enum":
        return f"{field['cpp_type']}::{value}"
    if kind in ("integer_array", "number_array"):
        values = ", ".join(repr(v) for v in value)
        return f"{{{values}}}"
    if isinstance(value, str):
        return json.dumps(value)
    if field["cpp_type"] == "float":
        return f"{value}f"
    if field["cpp_type"] == "std::uint64_t":
        return f"{value}ULL"
    return str(value)


def cpp_string(value):
    return json.dumps(str(value))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    schema = json.loads(SCHEMA.read_text())
    lines = [
        "// Generated by tools/generate_parameters.py; do not edit by hand.",
        "#pragma once", "", "#include <cstdint>", "#include <string>",
        "#include <vector>", "", "namespace spiking {", "",
        "enum class DelayDistribution { Uniform, FibonacciWeighted };", "",
    ]
    for group in schema["groups"]:
        lines.append(f"struct {group['cpp_struct']} {{")
        for field in group["fields"]:
            lines.append(f"    {field['cpp_type']} {field['name']} = {cpp_literal(field)};")
        if group["cpp_struct"] == "SimulationParameters":
            lines += [
                "", "    std::uint32_t neuron_count() const {",
                "        return excitatory_count + inhibitory_count;", "    }",
                "", "    static SimulationParameters small_test() {",
                "        SimulationParameters p;",
                "        p.excitatory_count = 8192;",
                "        p.inhibitory_count = 1024;",
                "        p.steps = 1000;",
                "        return p;", "    }",
            ]
        lines += ["};", ""]
    lines += [
        "enum class ParameterMutability { Runtime, StepBoundary, Reinitialize };",
        "struct ParameterDescriptor {",
        "    const char* group;", "    const char* name;", "    const char* type;",
        "    const char* default_value;", "    const char* minimum;", "    const char* maximum;",
        "    const char* unit;", "    ParameterMutability mutability;", "    const char* description;",
        "};", "",
        "inline constexpr ParameterDescriptor kParameterDescriptors[] = {",
    ]
    for group in schema["groups"]:
        for f in group["fields"]:
            default = json.dumps(f["default"], separators=(",", ":"))
            minimum = f.get("min", "")
            maximum = f.get("max", "")
            mutability = f["mutability"].replace("_", " ").title().replace(" ", "")
            lines.append(
                "    {" + ", ".join([
                    cpp_string(group["name"]), cpp_string(f["name"]),
                    cpp_string(f["type"]), cpp_string(default),
                    cpp_string(minimum), cpp_string(maximum),
                    cpp_string(f.get("unit", "")),
                    f"ParameterMutability::{mutability}",
                    cpp_string(f.get("description", "")),
                ]) + "},"
            )
    lines += ["};", "", "} // namespace spiking", ""]
    generated = "\n".join(lines)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Generated parameter header is stale. Run tools/generate_parameters.py")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
